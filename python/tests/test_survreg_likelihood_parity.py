_WIDTH = [1.0, 1.0, 0.5, 1.0, 1.0, 0.6, 1.0, 1.0, 1.0, 0.5, 1.0, 1.0]
_WEIGHT = [0.5, 1.0, 1.5, 2.0, 0.75, 1.25, 2.0, 0.5, 1.25, 0.75, 1.5, 1.0]
_OFFSET = [-0.25, 0.0, 0.25, 0.125, -0.125, 0.25, 0.0, -0.25, 0.125, 0.0, -0.125, 0.25]
_BINARY = [1, 0, 1, 1, 1, 1, 0, 1, 0, 1, 1, 1]
_MIXED = [1, 2, 3, 0, 1, 3, 1, 0, 2, 3, 1, 1]
_TRANSFORMED = {"weibull", "lognormal", "loglogistic"}


def _case_data(reference, repetitions=1):
    status = {
        "exact": [1] * len(_TIME),
        "right": _BINARY,
        "left": [2 - event for event in _BINARY],
        "interval": _MIXED,
    }[reference["censoring"]]
    upper = [time + width for time, width in zip(_TIME, _WIDTH, strict=True)]
    transformed = reference["distribution"] in _TRANSFORMED
    return {
        "time": ([math.exp(time) for time in _TIME] if transformed else _TIME) * repetitions,
        "time2": ([math.exp(time) for time in upper] if transformed else upper) * repetitions,
        "status": status * repetitions,
        "event": _BINARY * repetitions,
        "x": _X * repetitions,
        "weight": [weight / repetitions for weight in _WEIGHT] * repetitions,
        "offset": _OFFSET * repetitions,
        "group": ["A", "B"] * (6 * repetitions),
    }


def _fit_case(reference, *, facade=False, converge=False, repetitions=1):
    distribution = reference["distribution"]
    data = _case_data(reference, repetitions)
    fixed = reference["mode"] == "fixed"
    stratified = reference["mode"] == "strata"
    if facade:
        response = {
            "exact": "Surv(time)",
            "right": "Surv(time, event)",
            "left": "Surv(time, event, type='left')",
            "interval": "Surv(time, time2, status, type='interval')",
        }[reference["censoring"]]
        formula = f"{response} ~ x + offset(offset)"
        if stratified:
            formula += " + strata(group)"
        return survival.survreg(
            formula,
            data=data,
            weights=data["weight"],
            dist=distribution,
            init=reference["initial"],
            scale=1.25 if fixed else 0.0,
            parms=5.0 if distribution == "t" else None,
            max_iter=100 if converge else 0,
            eps=1e-13,
            score=True,
        )
    return survival.regression.survreg(
        data["time"],
        data["status"],
        [[1.0, x] for x in data["x"]],
        time2=data["time2"],
        weights=data["weight"],
        offsets=data["offset"],
        strata=[0, 1] * (6 * repetitions) if stratified else None,
        distribution=distribution,
        initial_beta=reference["initial"],
        fixed_scale=1.25 if fixed else None,
        distribution_parameter=5.0 if distribution == "t" else None,
        max_iter=100 if converge else 0,
        eps=1e-13,
    )


def _assert_reference_fit(fit, reference, *, converge=False):
    expected = reference["fit" if converge else "probe"]
    parameter_tolerance = 5e-8 if converge else 3e-11
    score_tolerance = 2e-7 if converge else 3e-10
    variance_tolerance = 2e-8 if converge else 3e-10
    assert fit.location_coefficients == pytest.approx(
        expected["coefficients"], rel=1e-8 if converge else 0, abs=parameter_tolerance
    )
    scales = expected["scales"]
    assert fit.scales == pytest.approx(
        scales if isinstance(scales, list) else [scales],
        rel=1e-8 if converge else 0,
        abs=parameter_tolerance,
    )
    assert survival.loglik(fit) == pytest.approx(expected["loglik"], rel=0, abs=3e-10)
    assert fit.score_vector == pytest.approx(expected["score"], rel=0, abs=score_tolerance)
    assert len(fit.variance_matrix) == len(expected["variance"])
    for actual, row in zip(fit.variance_matrix, expected["variance"], strict=True):
        assert actual == pytest.approx(row, rel=2e-7 if converge else 0, abs=variance_tolerance)

    # R coefficients and the recorded design/offsets determine every fitted
    # location; the response transformation supplies R's fitted response values.
    expected_lp = [
        expected["coefficients"][0] + x * expected["coefficients"][1] + offset
        for x, offset in zip(_X, _OFFSET, strict=True)
    ]
    assert fit.linear_predictors == pytest.approx(expected_lp, rel=2e-8, abs=parameter_tolerance)
    expected_response = (
        [math.exp(value) for value in expected_lp]
        if reference["distribution"] in _TRANSFORMED
        else expected_lp
    )
    assert fit.predict().predictions == pytest.approx(
        expected_response, rel=2e-7 if converge else 3e-11, abs=parameter_tolerance
    )
    if converge:
        assert fit.convergence_flag == 0
    else:
        assert fit.iterations == 0


