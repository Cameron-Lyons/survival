"""Optimizer likelihood, score, and observed-information parity with R survival.

Recorded fixtures use survival 3.8.11's survreg fitter, including its maxiter=0
evaluation at supplied parameters. They do not use diagnostic residual matrix
columns, whose interval scale derivatives follow different conventions.
The final tests use analytic references where R's fitter underflows or rounds
distinct log-transformed interval endpoints to the same value.
"""

