@pytest.mark.parametrize("facade", [False, True], ids=["native", "matrix"])
@pytest.mark.parametrize("repetitions", [1, 3334], ids=["sequential", "parallel"])
def test_zero_weight_overflowing_observation_does_not_change_fit(facade, repetitions):
    def fit(time, weights):
        common = {
            "time": time,
            "status": [1] * len(time),
            "covariates": [[1.0]] * len(time),
            "weights": weights,
            "max_iter": 100,
            "eps": 1e-12,
        }
        if facade:
            return survival.survreg(**common, dist="gaussian", init=[2.0, 0.0], score=True)
        return survival.regression.survreg(
            **common, distribution="gaussian", initial_beta=[2.0, 0.0]
        )

    baseline = fit([1.0, 2.0, 4.0], [1.0, 1.5, 0.75])
    expanded = fit(
        [1.0, 2.0, 4.0] * repetitions + [1e200],
        [weight / repetitions for weight in [1.0, 1.5, 0.75]] * repetitions + [0.0],
    )
    assert expanded.convergence_flag == baseline.convergence_flag == 0
    assert expanded.coefficients == pytest.approx(baseline.coefficients, rel=1e-9, abs=1e-10)
    assert expanded.log_likelihood == pytest.approx(baseline.log_likelihood, rel=0, abs=2e-10)
    assert expanded.score_vector == pytest.approx(baseline.score_vector, rel=0, abs=2e-9)
    for actual, expected in zip(expanded.variance_matrix, baseline.variance_matrix, strict=True):
        assert actual == pytest.approx(expected, rel=1e-9, abs=1e-10)
