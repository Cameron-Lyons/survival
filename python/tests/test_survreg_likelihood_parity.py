_R_REFERENCE_GENERATOR = r"""
library(survival)
stopifnot(packageVersion("survival") == "3.8.11")
d <- data.frame(
    time=c(1,1.5,2,2.5,3,3.4,3.8,4.1,4.5,5,5.4,6),
    x=c(-1,-.5,.5,1,-1,.25,-.75,.75,1,.1,-.2,.6),
    weight=c(.5,1,1.5,2,.75,1.25,2,.5,1.25,.75,1.5,1),
    offset=c(-.25,0,.25,.125,-.125,.25,0,-.25,.125,0,-.125,.25),
    group=rep(c("A", "B"),6))
d$upper <- d$time + c(1,1,.5,1,1,.6,1,1,1,.5,1,1)
binary <- c(1,0,1,1,1,1,0,1,0,1,1,1)
interval <- c(1,2,3,0,1,3,1,0,2,3,1,1)
extract_fit <- function(fit) list(
    coefficients=unname(coef(fit)), scales=unname(fit$scale),
    loglik=unname(fit$loglik[2]), score=unname(fit$score),
    variance=unname(fit$var))
references <- list()
for (dist in c("gaussian", "logistic", "extreme", "t", "lognormal", "loglogistic", "weibull")) {
    forms <- if(dist %in% c("lognormal", "loglogistic", "weibull")) "interval" else
        c("exact","right","left","interval")
    for (form in forms) for(mode in if(form=="interval") c("free","fixed","strata") else "free") {
        dd <- d
        if(dist %in% c("lognormal","loglogistic","weibull")) {
            dd$time <- exp(dd$time)
            dd$upper <- exp(dd$upper)
        }
        dd$status <- switch(form, exact=rep(1,12),right=binary,left=2-binary,interval=interval)
        y <- Surv(dd$time,dd$upper,dd$status,type="interval")
        formula <- if(mode=="strata") y ~ x + offset(offset) + strata(group) else
            y ~ x + offset(offset)
        scale <- if(mode=="fixed") 1.25 else 0
        parms <- if(dist=="t") 5 else NULL
        fitted <- survreg(formula,data=dd,weights=weight,dist=dist,scale=scale,parms=parms,
                          score=TRUE,control=survreg.control(maxiter=100,rel.tolerance=1e-13))
        init <- c(coef(fitted)+c(.08,-.05),
            if(scale==0) log(fitted$scale)+c(.04,-.03)[seq_along(fitted$scale)])
        probe <- survreg(formula,data=dd,weights=weight,dist=dist,scale=scale,parms=parms,
                         init=init,score=TRUE,control=survreg.control(maxiter=0))
        stopifnot(all(eigen(probe$var,symmetric=TRUE,only.values=TRUE)$values>0),
                  all(eigen(fitted$var,symmetric=TRUE,only.values=TRUE)$values>0))
        references[[paste(dist,form,mode,sep="/")]] <- list(
            distribution=dist,censoring=form,mode=mode,
            initial=unname(init),probe=extract_fit(probe),fit=extract_fit(fitted))
    }
}
cat(jsonlite::toJSON(references,auto_unbox=TRUE,digits=NA,pretty=TRUE))
"""

