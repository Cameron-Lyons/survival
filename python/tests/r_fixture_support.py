def record_outcome(test_id: str, kind: str, message: str) -> None:
    path = os.environ.get(COLLECT_ENV)
    if not path:
        return
    with open(path, "a", encoding="utf-8") as handle:
        handle.write(json.dumps({"id": test_id, "kind": kind, "message": message}) + "\n")
