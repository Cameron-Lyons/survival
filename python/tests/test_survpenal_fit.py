def _typed_data(data, columns=("age", "inst"), time="time"):
    """``Surv(time, status)`` with the design ``[1, *columns]``."""

    rows = [[1.0, *(data[c][i] for c in columns)] for i in range(len(data[time]))]
    return regression.SurvregData(list(data[time]), [int(s) - 1 for s in data["status"]], rows)


def _typed(data, penalty, pcols, dist="weibull", **kwargs):
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        return regression.survpenal_fit(
            data,
            regression.SurvregDistribution(dist),
            [penalty],
            pcols,
            **kwargs,
        )


def _check_typed(fit, ref, rel=1e-9, var_rel=1e-9):
    nvar = len(ref["coefficients"])
    assert fit.coefficients[:nvar] == approx(ref["coefficients"], rel)
    assert fit.scale == approx(ref["scale"], rel)
    assert fit.loglik == approx(ref["loglik"], rel)
    assert list(fit.iter) == ref["iter"]
    assert fit.df == approx(ref["df"], rel)
    assert fit.penalty[-1] == approx(ref["penalty"][-1], rel)
    assert fit.icoef == approx(ref["icoef"], rel)
    var = fit.var
    assert [var[i][i] for i in range(len(var))] == approx(ref["var_diag"], var_rel)
    assert fit.linear_predictors[:5] == approx(ref["lp"], rel)
    history = fit.history[0]
    assert history.theta == approx(ref["theta"], rel)
    assert history.done is ref["done"]
    if "history_rows" in ref:
        assert len(history.history) == ref["history_rows"]
        assert history.history[0] == approx(ref["history_first"], rel)
        assert history.history[-1] == approx(ref["history_last"], rel)
    if "frail" in ref:
        assert len(fit.frail) == ref["ngroups"]
        assert fit.frail[:3] == approx(ref["frail"], rel)
        assert fit.fvar[:3] == approx(ref["fvar"], var_rel)


