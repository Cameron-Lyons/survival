def _lung() -> dict[str, list[Any]]:
    lung = {k: list(v) for k, v in datasets.load_lung().items() if not k.startswith("_")}
    lung["off"] = [s / 10 for s in lung["sex"]]
    lung["w"] = [2.0 if a > 60 else 1.0 for a in lung["age"]]
    lung["agec2"] = [(a - 62) ** 2 / 100 for a in lung["age"]]
    lung["sex2"] = list(lung["sex"])
    lung["ltime"] = [math.log(t) for t in lung["time"]]
    lung["lc"] = [1.0 if s == 2 else 0.0 for s in lung["status"]]
    dead = [s == 2 for s in lung["status"]]
    time = lung["time"]
    lung["t1"] = [
        (t if i % 5 == 0 else max(t - 20, 1)) if d else t
        for i, (t, d) in enumerate(zip(time, dead, strict=True))
    ]
    lung["t2"] = [
        (t if i % 5 == 0 else t + 20) if d else None
        for i, (t, d) in enumerate(zip(time, dead, strict=True))
    ]
    lung["lt1"] = [math.log(t) for t in lung["t1"]]
    lung["lt2"] = [None if t is None else math.log(t) for t in lung["t2"]]
    return lung


