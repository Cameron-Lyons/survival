def approx(values, rel=1e-9):
    return pytest.approx(values, rel=rel, abs=1e-11, nan_ok=True)


def _check(fit, ref, rel=1e-9, var_rel=1e-9, lp=None):
    """Compares a fit with its reference: every component R's summary records."""

    assert fit.coefficients == approx(ref["coefficients"], rel)
    assert fit.scale == approx(ref["scale"], rel)
    assert fit.loglik == approx(ref["loglik"], rel)
    assert fit.iter == ref["iter"]
    assert fit.df == approx(ref["df"], rel)
    # the penalty of a theta near 1 amplifies round-off: compare it absolutely too
    assert fit.penalty == pytest.approx(ref["penalty"], rel=rel, abs=1e-8)
    assert fit.icoef == approx(ref["icoef"], rel)
    assert fit.df_residual == approx(ref["df_residual"], rel)
    var = fit.var
    assert [var[i][i] for i in range(len(var))] == approx(ref["var_diag"], var_rel)
    assert fit.var2[0][0] == approx(ref["var2_00"], var_rel)
    assert fit.linear_predictors[:5] == approx(ref["lp"] if lp is None else lp, rel)
    history = next(iter(fit.history.values()))
    assert history.theta == approx(ref["theta"], rel)
    assert history.done is ref["done"]
    if "history_rows" in ref:
        assert len(history.history) == ref["history_rows"]
        assert history.history[0] == approx(ref["history_first"], rel)
        assert history.history[-1] == approx(ref["history_last"], rel)


