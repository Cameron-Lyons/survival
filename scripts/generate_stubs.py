_SCALARS = {
    "f64": "float",
    "f32": "float",
    "usize": "int",
    "isize": "int",
    "u8": "int",
    "u16": "int",
    "u32": "int",
    "u64": "int",
    "i8": "int",
    "i16": "int",
    "i32": "int",
    "i64": "int",
    "bool": "bool",
    "String": "str",
    "str": "str",
    "char": "str",
    "IdValue": "int | float | str",
}
_ARRAY_NEWTYPES = {
    "FloatVec": ("ArrayLike", "NDArray[np.float64]"),
    "IntVec": ("ArrayLike", "NDArray[np.int32]"),
    "BoolVec": ("ArrayLike", "NDArray[np.bool_]"),
    "FloatMatrix": ("ArrayLike", "NDArray[np.float64]"),
}
_TRANSPARENT = {"PyResult", "SurvivalResult", "Result", "Box", "Arc", "Rc", "PyClassInitializer"}


def _parse_type(text: str) -> tuple[str, list[str]]:
    """Split ``Ident<a, b>`` into (ident, [args]); tuples/arrays/refs are normalised first."""
    text = text.strip()
    text = re.sub(r"^&\s*(?:'\w+\s+)?(?:mut\s+)?", "", text)
    text = re.sub(r"^(?:dyn|impl)\s+", "", text)
    if text.startswith("("):
        inner = text[1:-1] if text.endswith(")") else text[1:]
        return "()", _split_top_level(inner)
    if text.startswith("["):
        inner = text[1:-1]
        elem = _split_top_level(inner, ";")[0]
        return "[]", [elem]
    m = re.match(r"^([\w:]+)\s*(?:<(.*)>)?$", text, re.DOTALL)
    if m is None:
        return text, []
    ident = m.group(1).split("::")[-1]
    args = _split_top_level(m.group(2)) if m.group(2) else []
    args = [a for a in args if not a.startswith("'")]
    return ident, args


def rust_to_python(rust: str, classes: dict[str, str], ctx: str, self_name: str | None) -> str:
    """Map a Rust type to a Python annotation; ``ctx`` is 'param' or 'return'."""
    ident, args = _parse_type(rust)
    sub = lambda t: rust_to_python(t, classes, ctx, self_name)  # noqa: E731
    if ident == "()":
        if not args:
            return "None"
        return f"tuple[{', '.join(sub(a) for a in args)}]"
    if ident == "[]":
        return f"list[{sub(args[0])}]"
    if ident in _SCALARS:
        return _SCALARS[ident]
    if ident in _ARRAY_NEWTYPES:
        return _ARRAY_NEWTYPES[ident][0 if ctx == "param" else 1]
    if ident in {"PyReadonlyArray1", "PyReadonlyArray2", "PyArray1", "PyArray2"}:
        dtype = {"f64": "np.float64", "f32": "np.float32", "i32": "np.int32", "i64": "np.int64"}
        elem = next((dtype[a] for a in args if a in dtype), "Any")
        return f"NDArray[{elem}]"
    if ident == "Self" and self_name:
        return self_name
    if ident in _TRANSPARENT and args:
        return sub(args[0])
    if ident == "Option" and args:
        inner = sub(args[0])
        return inner if inner == "Any" else f"{inner} | None"
    if ident == "Vec" and args:
        inner = sub(args[0])
        return f"Sequence[{inner}]" if ctx == "param" else f"list[{inner}]"
    if ident in {"HashMap", "BTreeMap", "IndexMap"} and len(args) == 2:
        return f"dict[{sub(args[0])}, {sub(args[1])}]"
    if ident in {"HashSet", "BTreeSet"} and args:
        return f"set[{sub(args[0])}]"
    if ident == "Cow" and args:
        return sub(args[-1])
    if ident in {"Py", "PyRef", "PyRefMut", "Bound"} and args:
        target, _ = _parse_type(args[-1])
        if target == "PyAny":
            return "Any"
        if target == "PyDict":
            return "dict[str, Any]"
        if target == "PyList":
            return "list[Any]"
        if target == "PyTuple":
            return "tuple[Any, ...]"
        if target == "PyFunction":
            return "Callable[..., Any]"
        if target in classes:
            return classes[target]
        return "Any"
    if ident in {"PyObject", "PyAny"}:
        return "Any"
    if ident == "PyDict":
        return "dict[str, Any]"
    if ident in classes:
        return classes[ident]
    if ident in TYPE_ALIASES and not args:
        return sub(TYPE_ALIASES[ident])
    return "Any"


