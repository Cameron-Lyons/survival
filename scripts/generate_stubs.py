@dataclass
class RustFn:
    ident: str
    py_name: str
    params: list[tuple[str, str]]  # (name, rust type), self/py params removed
    ret: str
    kind: str = "method"  # method | static | class | new | getter | setter | function


@dataclass
class RustClass:
    ident: str
    py_name: str
    fields: dict[str, tuple[str, bool]] = field(default_factory=dict)  # name -> (type, settable)
    methods: dict[str, RustFn] = field(default_factory=dict)
    getters: dict[str, str] = field(default_factory=dict)
    setters: set[str] = field(default_factory=set)
    new: RustFn | None = None
    is_enum: bool = False


_BLOCK_COMMENT_RE = re.compile(r"/\*.*?\*/", re.DOTALL)
_LINE_COMMENT_RE = re.compile(r"//[^\n]*")


def _strip_comments(source: str) -> str:
    source = _BLOCK_COMMENT_RE.sub("", source)
    return _LINE_COMMENT_RE.sub("", source)


def _matching(source: str, start: int, open_ch: str, close_ch: str) -> int:
    """Index just past the bracket that closes the one at ``start``."""
    depth = 0
    i = start
    while i < len(source):
        ch = source[i]
        if ch == open_ch:
            depth += 1
        elif ch == close_ch:
            depth -= 1
            if depth == 0:
                return i + 1
        elif ch == '"':
            i = _skip_string(source, i)
            continue
        i += 1
    raise ValueError("unbalanced brackets")


def _skip_string(source: str, i: int) -> int:
    i += 1
    while i < len(source):
        if source[i] == "\\":
            i += 2
            continue
        if source[i] == '"':
            return i + 1
        i += 1
    return i


def _read_attributes(source: str, pos: int) -> tuple[list[str], int]:
    """Read consecutive ``#[...]`` attributes starting at ``pos``; return (attrs, new pos)."""
    attrs: list[str] = []
    while True:
        m = re.compile(r"\s*#\s*\[").match(source, pos)
        if m is None:
            return attrs, pos
        end = _matching(source, m.end() - 1, "[", "]")
        attrs.append(source[m.end() : end - 1].strip())
        pos = end


def _attr_name_override(attrs: list[str], attr_prefix: str) -> str | None:
    for attr in attrs:
        if attr.startswith(attr_prefix):
            m = re.search(r'\bname\s*=\s*"([^"]+)"', attr)
            if m:
                return m.group(1)
    return None


def _split_top_level(text: str, sep: str = ",") -> list[str]:
    parts: list[str] = []
    depth = 0
    current: list[str] = []
    for ch in text:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(ch)
    if "".join(current).strip():
        parts.append("".join(current))
    return [p.strip() for p in parts if p.strip()]


def _parse_fn(source: str, pos: int) -> tuple[RustFn | None, int]:
    """Parse ``fn ident<...>(params) -> ret`` at ``pos``; return (fn, position after signature)."""
    m = re.compile(r"\s*(?:pub(?:\([^)]*\))?\s+)?(?:const\s+)?(?:unsafe\s+)?fn\s+(r#)?(\w+)").match(
        source, pos
    )
    if m is None:
        return None, pos
    ident = m.group(2)
    i = m.end()
    if source[i : i + 1] == "<":
        i = _matching(source, i, "<", ">")
    if source[i : i + 1] != "(":
        return None, pos
    close = _matching(source, i, "(", ")")
    raw_params = source[i + 1 : close - 1]
    j = close
    ret = "()"
    tail = re.compile(r"\s*->").match(source, j)
    if tail:
        k = tail.end()
        depth = 0
        start = k
        while k < len(source):
            ch = source[k]
            if ch in "<([":
                depth += 1
            elif ch in ">)]":
                depth -= 1
            elif ch in "{;" and depth == 0:
                break
            k += 1
        ret = source[start:k].strip()
        j = k
    where = re.compile(r"\s*where\b[^{;]*").match(source, j)
    if where:
        j = where.end()
    params: list[tuple[str, str]] = []
    for part in _split_top_level(raw_params):
        if re.match(r"^(&\s*(mut\s+)?)?(mut\s+)?self$", part) or re.match(
            r"^(mut\s+)?self\s*:", part
        ):
            continue
        if ":" not in part:
            continue
        name, _, typ = part.partition(":")
        name = name.strip().removeprefix("mut ").strip().removeprefix("r#")
        typ = typ.strip()
        if re.match(r"^(&\s*)?Python\b", typ) or name in {"py", "_py"}:
            continue
        if re.match(r"^(&\s*)?(Bound<[^>]*PyType>|Py<PyType>)", typ) or name == "cls":
            continue
        if re.match(r"^(&\s*)?PyRef(Mut)?<['a-z_ ]*Self>", typ) or name in {"slf", "this"}:
            continue
        params.append((name, typ))
    return RustFn(ident=ident, py_name=ident, params=params, ret=ret), j


def _skip_item_body(source: str, pos: int) -> int:
    """Skip a ``{ ... }`` body or a ``;`` at ``pos``."""
    m = re.compile(r"\s*").match(source, pos)
    pos = m.end() if m else pos
    if source[pos : pos + 1] == "{":
        return _matching(source, pos, "{", "}")
    if source[pos : pos + 1] == ";":
        return pos + 1
    return pos


def _parse_struct_fields(body: str, get_all: bool) -> dict[str, tuple[str, bool]]:
    fields: dict[str, tuple[str, bool]] = {}
    pos = 0
    while pos < len(body):
        attrs, pos = _read_attributes(body, pos)
        m = re.compile(r"\s*(?:pub(?:\([^)]*\))?\s+)?(r#)?(\w+)\s*:").match(body, pos)
        if m is None:
            # tuple struct entries or trailing whitespace
            nxt = body.find(",", pos)
            if nxt == -1:
                break
            pos = nxt + 1
            continue
        name = m.group(2)
        start = m.end()
        depth = 0
        k = start
        while k < len(body):
            ch = body[k]
            if ch in "<([":
                depth += 1
            elif ch in ">)]":
                depth -= 1
            elif ch == "," and depth == 0:
                break
            k += 1
        typ = body[start:k].strip()
        pos = k + 1
        pyo3 = [a for a in attrs if a.startswith("pyo3")]
        exposed = get_all or any(re.search(r"\bget\b", a) for a in pyo3)
        if not exposed:
            continue
        settable = any(re.search(r"\bset\b", a) for a in pyo3)
        py_name = _attr_name_override(pyo3, "pyo3") or name
        fields[py_name] = (typ, settable)
    return fields


def _parse_methods(body: str, cls: RustClass) -> None:
    pos = 0
    while pos < len(body):
        attrs, pos = _read_attributes(body, pos)
        fn, after = _parse_fn(body, pos)
        if fn is None:
            m = re.compile(r"\s*\S").match(body, pos)
            if m is None:
                break
            # skip a non-fn item (const, type, ...)
            semi = body.find(";", pos)
            brace = body.find("{", pos)
            if semi == -1 and brace == -1:
                break
            if brace != -1 and (semi == -1 or brace < semi):
                pos = _matching(body, brace, "{", "}")
            else:
                pos = semi + 1
            continue
        pos = _skip_item_body(body, after)
        py_name = _attr_name_override(attrs, "pyo3") or fn.ident
        if any(a == "new" for a in attrs):
            fn.kind = "new"
            fn.py_name = "__init__"
            cls.new = fn
        elif any(a.startswith("getter") for a in attrs):
            getter_attr = next(a for a in attrs if a.startswith("getter"))
            m = re.match(r"getter\s*\(\s*(\w+)\s*\)", getter_attr)
            # PyO3 strips a `get_` prefix from an unnamed getter
            name = m.group(1) if m else py_name.removeprefix("get_")
            cls.getters[name] = fn.ret
        elif any(a.startswith("setter") for a in attrs):
            setter_attr = next(a for a in attrs if a.startswith("setter"))
            m = re.match(r"setter\s*\(\s*(\w+)\s*\)", setter_attr)
            name = m.group(1) if m else py_name.removeprefix("set_")
            cls.setters.add(name)
        else:
            if any(a == "staticmethod" for a in attrs):
                fn.kind = "static"
            elif any(a == "classmethod" for a in attrs):
                fn.kind = "class"
            fn.py_name = py_name
            cls.methods[py_name] = fn


TYPE_ALIASES: dict[str, str] = {}
_TYPE_ALIAS_RE = re.compile(
    r"^\s*(?:pub(?:\([^)]*\))?\s+)?type\s+(\w+)\s*=\s*([^;]+);", re.MULTILINE
)


def parse_rust_sources(src: Path = SRC) -> tuple[dict[str, RustClass], dict[str, RustFn]]:
    classes_by_ident: dict[str, RustClass] = {}
    functions: dict[str, RustFn] = {}
    pending_methods: list[tuple[str, str]] = []

    for path in sorted(src.rglob("*.rs")):
        if "tests" in path.parts or path.name == "registration_audit.rs":
            continue
        source = _strip_comments(path.read_text())

        for m in _TYPE_ALIAS_RE.finditer(source):
            TYPE_ALIASES.setdefault(m.group(1), " ".join(m.group(2).split()))

        for m in re.finditer(r"#\s*\[\s*pyclass\b", source):
            attrs, pos = _read_attributes(source, m.start())
            pyclass_attr = next(a for a in attrs if a.startswith("pyclass"))
            head = re.compile(r"\s*(?:pub(?:\([^)]*\))?\s+)?(struct|enum)\s+(\w+)").match(
                source, pos
            )
            if head is None:
                continue
            kind, ident = head.group(1), head.group(2)
            py_name = _attr_name_override([pyclass_attr], "pyclass") or ident
            cls = RustClass(ident=ident, py_name=py_name, is_enum=kind == "enum")
            i = head.end()
            if source[i : i + 1] == "<":
                i = _matching(source, i, "<", ">")
            ws = re.compile(r"\s*").match(source, i)
            i = ws.end() if ws else i
            if source[i : i + 1] == "{":
                end = _matching(source, i, "{", "}")
                if kind == "struct":
                    get_all = re.search(r"\bget_all\b", pyclass_attr) is not None
                    cls.fields = _parse_struct_fields(source[i + 1 : end - 1], get_all)
            classes_by_ident[ident] = cls

        for m in re.finditer(r"#\s*\[\s*pymethods\s*\]", source):
            attrs, pos = _read_attributes(source, m.start())
            head = re.compile(r"\s*impl\s+(?:<[^>]*>\s*)?(\w+)").match(source, pos)
            if head is None:
                continue
            i = source.find("{", head.end())
            end = _matching(source, i, "{", "}")
            pending_methods.append((head.group(1), source[i + 1 : end - 1]))

        for m in re.finditer(r"#\s*\[\s*pyfunction\b", source):
            attrs, pos = _read_attributes(source, m.start())
            fn, _ = _parse_fn(source, pos)
            if fn is None:
                continue
            py_name = _attr_name_override(attrs, "pyfunction") or _attr_name_override(attrs, "pyo3")
            fn.py_name = py_name or fn.ident
            fn.kind = "function"
            functions[fn.py_name] = fn

    for ident, body in pending_methods:
        cls = classes_by_ident.get(ident)
        if cls is None:
            cls = RustClass(ident=ident, py_name=ident)
            classes_by_ident[ident] = cls
        _parse_methods(body, cls)

    classes = {cls.py_name: cls for cls in classes_by_ident.values()}
    return classes, functions


