def _format_def(
    name: str, params: list[Param], ret: str, indent: str, decorators: list[str], self_arg: str
) -> str:
    rendered: list[str] = []
    if self_arg:
        rendered.append(self_arg)
    seen_star = False
    for p in params:
        if p.kind == "keyword" and not seen_star:
            rendered.append("*")
            seen_star = True
        if p.kind == "vararg":
            rendered.append(f"*{p.name}: Any")
            seen_star = True
            continue
        if p.kind == "kwarg":
            rendered.append(f"**{p.name}: Any")
            continue
        annotation = p.annotation
        if p.default == "None" and annotation != "Any" and not annotation.endswith("| None"):
            annotation = f"{annotation} | None"
        text = f"{p.name}: {annotation}"
        if p.default is not None:
            text += f" = {p.default}"
        rendered.append(text)
    lines = [f"{indent}{d}" for d in decorators]
    one_line = f"{indent}def {name}({', '.join(rendered)}) -> {ret}: ..."
    if len(one_line) <= LINE_LENGTH:
        lines.append(one_line)
        return "\n".join(lines)
    if rendered:
        lines.append(f"{indent}def {name}(")
        for item in rendered:
            lines.append(f"{indent}    {item},")
        closing = f"{indent}) -> {ret}: ..."
    else:
        closing = one_line
    if len(closing) <= LINE_LENGTH:
        lines.append(closing)
    else:
        lines.extend(_wrap_return(closing, ret, indent))
    return "\n".join(lines)


def _wrap_return(closing: str, ret: str, indent: str) -> list[str]:
    """Split an over-long ``) -> outer[inner]: ...`` line the way ruff's formatter does: the
    outermost subscript is opened at the end of the line, its contents go on one indented line
    when they fit (else one item per line with a trailing comma), and ``]: ...`` closes it.

    Keeping this in the generator (rather than relying on ``ruff format``) makes the output
    identical whether or not ruff is installed; ``_ruff_format`` verifies that it stays so.
    """
    head, bracket, rest = ret.partition("[")
    if not bracket or not rest.endswith("]"):
        return [closing]  # not a subscript: nothing ruff would split, leave it long
    prefix = closing[: len(closing) - len(f"{ret}: ...")]  # everything before the annotation
    inner = rest[:-1]
    lines = [f"{prefix}{head}["]
    body = f"{indent}    {inner}"
    if len(body) <= LINE_LENGTH:
        lines.append(body)
    else:
        lines.extend(f"{indent}    {item}," for item in _split_top_level(inner))
    lines.append(f"{indent}]: ...")
    return lines


def _annotate(
    params: list[Param], rust_fn: RustFn | None, classes: dict[str, str], self_name: str | None
) -> None:
    if rust_fn is None:
        return
    names = [p.name for p in params if p.kind in {"positional", "keyword"}]
    rust_names = [n for n, _ in rust_fn.params]
    if names != rust_names:
        return
    types = dict(rust_fn.params)
    for p in params:
        if p.name in types:
            p.annotation = rust_to_python(types[p.name], classes, "param", self_name)


def render_stub(
    core, manifest_names: list[str], classes: dict[str, RustClass], functions, verbose=False
) -> str:
    class_names = {cls.ident: cls.py_name for cls in classes.values()}
    class_names.update(
        {name: name for name in manifest_names if isinstance(getattr(core, name), type)}
    )
    blocks: list[str] = []
    missing_types: list[str] = []

    for name in manifest_names:
        obj = getattr(core, name)
        if isinstance(obj, type):
            blocks.append(_render_class(name, obj, classes.get(name), class_names, missing_types))
        else:
            blocks.append(
                _render_function(name, obj, functions.get(name), class_names, missing_types)
            )
    if verbose and missing_types:
        print("no Rust type found for:", ", ".join(missing_types), file=sys.stderr)
    body = _join_blocks(blocks)
    return HEADER + "\n" + _imports(body) + "\n" + body + "\n"


def _join_blocks(blocks: list[str]) -> str:
    """Ruff's stub layout: consecutive top-level ``def``s touch, classes are separated by one
    blank line."""
    out: list[str] = []
    for index, block in enumerate(blocks):
        if index:
            touching = blocks[index - 1].startswith("def ") and block.startswith("def ")
            out.append("\n" if touching else "\n\n")
        out.append(block)
    return "".join(out)


def _render_function(name, obj, rust_fn, class_names, missing_types) -> str:
    text = _text_signature(obj) or "(*args, **kwargs)"
    params = parse_text_signature(text)
    _annotate(params, rust_fn, class_names, None)
    if name in RETURN_OVERRIDES:
        ret = RETURN_OVERRIDES[name]
    elif name.startswith("load_"):
        # the dataset loaders are macro-generated: one dict of column lists per data frame
        ret = "dict[str, list[Any]]"
    elif rust_fn is not None:
        ret = rust_to_python(rust_fn.ret, class_names, "return", None)
    else:
        ret = "Any"
        missing_types.append(name)
    return _format_def(name, params, ret, "", [], "")


def _render_class(name, cls, rust_cls, class_names, missing_types) -> str:
    """One class block; members are ordered deterministically because PyO3's type ``__dict__``
    order is not stable across processes: variants, ``__init__``, dunders, methods, properties,
    each group alphabetical."""
    lines = [f"class {name}:"]
    members: list[str] = []
    variants = sorted(k for k, v in cls.__dict__.items() if isinstance(v, cls))
    for variant in variants:
        if keyword.iskeyword(variant):
            # e.g. ScreeningRule.None: only reachable through getattr
            continue
        members.append(f"    {variant}: {name}")

    init_text = cls.__text_signature__
    if init_text is not None:
        params = parse_text_signature(init_text)
        _annotate(params, rust_cls.new if rust_cls else None, class_names, name)
        members.append(_format_def("__init__", params, "None", "    ", [], "self"))

    dunders: list[str] = []
    methods: list[str] = []
    properties: list[str] = []
    for key, value in sorted(cls.__dict__.items()):
        if key in _SKIP_MEMBERS or key in _COMPARISONS or key in variants:
            continue
        if keyword.iskeyword(key):
            # e.g. FastCoxConfig.lambda: only reachable through getattr, not declarable in a stub
            continue
        if key.startswith("__") and key.endswith("__"):
            if key in _DUNDER_METHODS:
                text = _text_signature(value)
                params = parse_text_signature(text) if text else []
                dunders.append(_format_def(key, params, _DUNDER_METHODS[key], "    ", [], "self"))
            continue
        type_name = type(value).__name__
        if type_name == "getset_descriptor":
            ret, settable = "Any", False
            if rust_cls is not None:
                if key in rust_cls.fields:
                    rust_type, settable = rust_cls.fields[key]
                    ret = rust_to_python(rust_type, class_names, "return", name)
                elif key in rust_cls.getters:
                    ret = rust_to_python(rust_cls.getters[key], class_names, "return", name)
                    settable = key in rust_cls.setters
                else:
                    missing_types.append(f"{name}.{key}")
            else:
                missing_types.append(f"{name}.{key}")
            properties.append("    @property")
            properties.append(f"    def {key}(self) -> {ret}: ...")
            if settable:
                properties.append(f"    @{key}.setter")
                properties.append(f"    def {key}(self, value: {ret}) -> None: ...")
        elif type_name in {"method_descriptor", "builtin_function_or_method"} or isinstance(
            value, (staticmethod, classmethod)
        ):
            text = _text_signature(value) or "(*args, **kwargs)"
            params = parse_text_signature(text)
            rust_fn = rust_cls.methods.get(key) if rust_cls else None
            _annotate(params, rust_fn, class_names, name)
            ret = rust_to_python(rust_fn.ret, class_names, "return", name) if rust_fn else "Any"
            if rust_fn is None:
                missing_types.append(f"{name}.{key}")
            if isinstance(value, staticmethod):
                methods.append(_format_def(key, params, ret, "    ", ["@staticmethod"], ""))
            elif isinstance(value, classmethod):
                methods.append(_format_def(key, params, ret, "    ", ["@classmethod"], "cls"))
            else:
                methods.append(_format_def(key, params, ret, "    ", [], "self"))
    members.extend(dunders)
    members.extend(methods)
    members.extend(properties)
    if not members:
        members.append("    ...")
    lines.extend(members)
    return "\n".join(lines)


