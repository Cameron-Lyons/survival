"""Generate ``python/survival/_survival.pyi`` from the built extension.

The *structure* of the stub (which names exist, constructor/method/function signatures with
their defaults, ``#[pyo3(get)]`` properties, enum variants) is introspected from the compiled
``survival._survival`` module, so it is exactly the runtime surface.  The *types* are inferred
from the Rust sources: ``#[pyo3(get)]`` field declarations, ``#[pymethods]`` signatures and
``#[pyfunction]`` signatures are parsed and their Rust types mapped to Python annotations
(``Vec<f64>`` -> ``list[float]``, ``Option<T>`` -> ``T | None``, pyclass names -> the class,
...); anything that cannot be resolved is ``Any``.

Usage::

    python3 scripts/generate_stubs.py            # rewrite python/survival/_survival.pyi
    python3 scripts/generate_stubs.py --check    # exit 1 if the stub is stale

The extension must be importable with every manifest symbol present (build it with
``maturin develop --features extension-module,ml``), because the manifest is the list of names
that must be typed.  ``python/tests/test_binding_contract.py`` checks, for every manifest name,
that the stub's signatures agree with ``inspect.signature`` of the runtime object.
"""

