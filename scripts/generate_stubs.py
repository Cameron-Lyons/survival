@dataclass
class Param:
    name: str
    kind: str  # positional-only handled as positional-or-keyword in stubs
    default: str | None
    annotation: str = "Any"


def parse_text_signature(text: str) -> list[Param]:
    text = re.sub(r"\$(self|cls|type|module)\s*,?\s*", "", text)
    text = text.strip()
    if text.startswith("(") and text.endswith(")"):
        text = text[1:-1]
    # a bare positional-only marker is left behind by `($self, /)`
    text = re.sub(r"^\s*/\s*$", "", text)
    tree = ast.parse(f"def _f({text}): pass")
    fn = tree.body[0]
    if not isinstance(fn, ast.FunctionDef):  # pragma: no cover - the source above is a def
        raise TypeError(f"unexpected signature text {text!r}")
    params: list[Param] = []
    args = fn.args
    positional = list(args.posonlyargs) + list(args.args)
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    for arg, default in zip(positional, defaults, strict=True):
        params.append(Param(arg.arg, "positional", _render_default(default)))
    if args.vararg is not None:
        params.append(Param(args.vararg.arg, "vararg", None))
    for arg, default in zip(args.kwonlyargs, args.kw_defaults, strict=True):
        params.append(Param(arg.arg, "keyword", _render_default(default)))
    if args.kwarg is not None:
        params.append(Param(args.kwarg.arg, "kwarg", None))
    return params


def _render_default(node: ast.AST | None) -> str | None:
    if node is None:
        return None
    if isinstance(node, ast.Constant):
        value = node.value
        if value is Ellipsis:
            return "..."
        if isinstance(value, str):
            return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
        if isinstance(value, float):
            return repr(value)
        return repr(value)
    return ast.unparse(node)


def _text_signature(obj: object) -> str | None:
    text = getattr(obj, "__text_signature__", None)
    if text is None and isinstance(obj, (staticmethod, classmethod)):
        text = getattr(obj.__func__, "__text_signature__", None)
    return text


