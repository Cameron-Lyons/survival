def _imports(body: str) -> str:
    """Only the imports the rendered body uses (ruff flags unused ones)."""
    abc = [name for name in ("Callable", "Sequence") if f"{name}[" in body]
    lines = []
    if abc:
        lines.append(f"from collections.abc import {', '.join(abc)}")
    lines.append("from typing import Any")
    numpy_typing = [name for name in ("ArrayLike", "NDArray") if re.search(rf"\b{name}\b", body)]
    uses_np = "np." in body
    if uses_np or numpy_typing:
        lines.append("")
        if uses_np:
            lines.append("import numpy as np")
        if numpy_typing:
            lines.append(f"from numpy.typing import {', '.join(numpy_typing)}")
    return "\n".join(lines) + "\n"


