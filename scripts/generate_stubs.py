def load_extension():
    """The built extension: the installed package (a wheel, or `maturin develop`), else the
    source tree with the extension built into it."""

    try:
        return importlib.import_module("survival._survival")
    except ImportError:
        sys.path.insert(0, str(ROOT / "python"))
        return importlib.import_module("survival._survival")


def manifest_names() -> list[str]:
    manifest = runpy.run_path(str(MANIFEST_PATH))
    return sorted(manifest["BINDINGS"])


def generate(verbose: bool = False) -> str:
    core = load_extension()
    names = manifest_names()
    absent = [n for n in names if not hasattr(core, n)]
    if absent:
        raise SystemExit(
            "the extension lacks manifest symbols (build it with "
            "`maturin develop --features extension-module,ml`): " + ", ".join(absent[:10])
        )
    classes, functions = parse_rust_sources()
    return _ruff_format(render_stub(core, names, classes, functions, verbose=verbose))


def _ruff_command() -> list[str]:
    """``ruff`` from PATH, else the one installed next to this interpreter (CI runs
    ``.venv/bin/python`` without activating the venv), else a loud failure -- never silently
    emit unverified text, because the checked-in stub must not depend on the caller's PATH."""
    ruff = shutil.which("ruff")
    if ruff is not None:
        return [ruff]
    if importlib.util.find_spec("ruff") is not None:
        return [sys.executable, "-m", "ruff"]
    raise SystemExit(
        "ruff is required to verify the generated stub's layout; install it into this "
        "interpreter's environment (`pip install ruff` / `uv pip install ruff`)"
    )


def _ruff_format(text: str) -> str:
    """Run ``ruff format`` over the rendered stub and require it to be a no-op.

    The emitters above already produce ruff's layout, so the generator's output is the same with
    or without ruff; ruff only proves that.  A difference means an emitter fell out of step with
    the formatter (or ruff changed), and is reported rather than papered over so the stub cannot
    depend on which ruff, if any, happens to be on PATH.
    """
    result = subprocess.run(  # noqa: S603 - ruff from PATH or this interpreter, fixed arguments
        [*_ruff_command(), "format", "--stdin-filename", str(STUB_PATH), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=False,
        cwd=ROOT,
    )
    if result.returncode != 0:
        raise SystemExit(f"ruff format failed on the generated stub:\n{result.stderr}")
    if result.stdout != text:
        diff = "".join(
            difflib.unified_diff(
                text.splitlines(keepends=True),
                result.stdout.splitlines(keepends=True),
                fromfile="generate_stubs.py output",
                tofile="ruff format",
                n=1,
            )
        )
        raise SystemExit(
            "scripts/generate_stubs.py emitted text that ruff would reformat; teach the emitter "
            "(_format_def / _wrap_return / _join_blocks) the formatter's layout:\n" + diff
        )
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the stub is stale")
    parser.add_argument(
        "--verbose", action="store_true", help="list the symbols whose Rust type was not found"
    )
    args = parser.parse_args()
    expected = generate(verbose=args.verbose)
    if args.check:
        actual = STUB_PATH.read_text() if STUB_PATH.exists() else ""
        if actual != expected:
            sys.stderr.writelines(
                difflib.unified_diff(
                    actual.splitlines(keepends=True),
                    expected.splitlines(keepends=True),
                    fromfile=str(STUB_PATH),
                    tofile=f"{STUB_PATH} (generated)",
                )
            )
            return 1
        return 0
    STUB_PATH.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
